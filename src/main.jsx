import React from 'react';
import { createRoot } from 'react-dom/client';
import { Presenter, PresenterOutput } from './Presenter.jsx';
import './base.css';
import{installPrototypeAdapter}from'./prototype-adapter.js';
const isOutput=['/presenter-output','/network-output'].includes(location.pathname);
const prototypeMode=new URLSearchParams(location.search).get('prototype')==='1'||import.meta.env.VITE_PROTOTYPE==='true';
if(prototypeMode)installPrototypeAdapter();
if(isOutput)document.documentElement.classList.add('slc-output-page');
const view=isOutput?<PresenterOutput/>:<Presenter/>;
createRoot(document.getElementById('root')).render(view);
